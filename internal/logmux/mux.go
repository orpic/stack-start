package logmux

import (
	"io"
	"sync"

	"github.com/fatih/color"
	"github.com/orpic/stack-start/internal/output"
)

// MarkerPrefix starts every line stackstart itself writes into a process's
// log, so markers are easy to grep for and never confused with process output.
const MarkerPrefix = "[stackstart] "

// Mux fans out log lines from a process to a file writer and the console.
type Mux struct {
	name          string
	padTo         int
	clr           *color.Color
	faint         *color.Color
	fileWriter    io.Writer
	consoleWriter io.Writer
	consoleMu     *sync.Mutex
}

// New creates a Mux. The consoleMu must be shared across all Mux instances
// in a session to prevent torn console lines.
func New(name string, padTo int, fileWriter, consoleWriter io.Writer, consoleMu *sync.Mutex) *Mux {
	return &Mux{
		name:          name,
		padTo:         padTo,
		clr:           color.New(ColorFor(name)),
		faint:         color.New(color.Faint),
		fileWriter:    fileWriter,
		consoleWriter: consoleWriter,
		consoleMu:     consoleMu,
	}
}

// Write writes a sanitized line: its plain text to the log file and its
// console form, prefixed with the process name, to the console.
func (m *Mux) Write(l output.Line) {
	_, _ = io.WriteString(m.fileWriter, l.Plain+"\n")
	m.console(l.Console)
}

// WriteLine sanitizes and writes one raw line.
func (m *Mux) WriteLine(line []byte) {
	m.Write(output.Sanitize(line))
}

// Marker writes a line generated by stackstart (not by the process) into the
// process's log and onto the console, e.g. "[stackstart] screen cleared".
func (m *Mux) Marker(text string) {
	_, _ = io.WriteString(m.fileWriter, MarkerPrefix+text+"\n")
	m.console([]byte(m.faint.Sprint(MarkerPrefix + text)))
}

func (m *Mux) console(line []byte) {
	prefix := m.clr.Sprint(FormatPrefix(m.name, m.padTo))
	m.consoleMu.Lock()
	_, _ = m.consoleWriter.Write([]byte(prefix))
	_, _ = m.consoleWriter.Write(line)
	_, _ = m.consoleWriter.Write([]byte("\n"))
	m.consoleMu.Unlock()
}
